import {Hono} from 'hono';
import {z} from 'zod';
import {type AppEnv,type Env,initialize,HttpError,localized,localeFor,validSlug,fail,now,platformRequest,requestLimit} from './security';
import {authRoutes,sessionResult} from './routes/auth';
import {siteRoutes,searchRoutes} from './routes/sites';
import {mediaRoutes} from './routes/media';
import {adminRoutes} from './routes/admin';
import {blogRoutes,notificationRoutes} from './routes/content';
import {reserveRoutes} from './routes/reserves';
import {featureRoutes,adminFeatureRoutes} from './routes/features';
import {isReservedName} from './services/reserves';
import {managedRoutes} from './routes/managed';
import {pushRoutes} from './routes/push';
export type {Env} from './security';
export {getSession} from './security';
export const apiApp=new Hono<AppEnv>();
apiApp.use('*',initialize);
apiApp.onError((error,c)=>{const known=error instanceof HttpError;if(!known)console.error('VIP_API_FAILURE',error instanceof Error?error.name:'Error');return c.json({error:localized(known?error.code:'SERVICE_UNAVAILABLE',localeFor(c)),code:known?error.code:'SERVICE_UNAVAILABLE'},known?error.status:503);});
apiApp.notFound(c=>c.json({error:localized('NOT_FOUND',localeFor(c)),code:'NOT_FOUND'},404));
apiApp.get('/session',async c=>{if(!platformRequest(c))return c.json({user:null,csrf:null,site:null});const user=c.get('user'),session=c.get('session');return c.json(user&&session?await sessionResult(c,user,session.csrf):{user:null,csrf:null,site:null});});
apiApp.get('/availability',async c=>{const parsed=z.string().max(63).safeParse(c.req.query('slug'));if(!parsed.success)fail('INVALID_INPUT');const slug=parsed.data.toLowerCase();if(!validSlug(slug))return c.json({slug,available:false});if(!c.env.DB)fail('SERVICE_UNAVAILABLE',503);const reserved=await isReservedName(c.env,slug);const site=await c.env.DB.prepare('SELECT id FROM sites WHERE slug=?').bind(slug).first();const reservation=await c.env.DB.prepare('SELECT slug FROM slug_reservations WHERE slug=? AND expires_at>?').bind(slug,now()).first();return c.json({slug,available:!reserved&&!site&&!reservation});});
apiApp.get('/settings',async c=>{if(!c.env.DB)fail('SERVICE_UNAVAILABLE',503);const settings=await c.env.DB.prepare('SELECT home_locked,platform_locked FROM settings WHERE id=1').first<{home_locked:number;platform_locked:number}>();if(!settings)fail('SERVICE_UNAVAILABLE',503);return c.json({homeLocked:!!settings.home_locked,platformLocked:!!settings.platform_locked});});
// Auth/mutation handlers never run on a tenant origin. No wildcard CORS or identity headers.
apiApp.use('/auth/*',async(c,next)=>{if(!platformRequest(c))fail('ORIGIN',403);await next();});
apiApp.route('/auth',authRoutes);
apiApp.route('/sites',siteRoutes);
apiApp.route('/search',searchRoutes);
apiApp.route('/media',mediaRoutes);
apiApp.route('/admin/reserves',reserveRoutes);
apiApp.route('/admin/features',adminFeatureRoutes);
apiApp.route('/features',featureRoutes);
apiApp.route('/admin/managed',managedRoutes);
apiApp.route('/admin',adminRoutes);
apiApp.route('/blogs',blogRoutes);
apiApp.route('/notifications',notificationRoutes);
apiApp.route('/push',pushRoutes);
